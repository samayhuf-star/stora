// Bundles drizzle-kit's generated .sql files into a TS module so migrations
// ship inside the compiled package (no filesystem lookups at runtime).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'drizzle');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();

const migrations = files.map((f) => ({
  id: f.replace(/\.sql$/, ''),
  statements: readFileSync(join(dir, f), 'utf8')
    .split('--> statement-breakpoint')
    .map((s) => s.trim())
    .filter(Boolean),
}));

const out =
  '// AUTO-GENERATED by scripts/gen-migrations.mjs - do not edit.\n' +
  'export interface Migration { id: string; statements: string[] }\n' +
  'export const migrations: Migration[] = ' +
  JSON.stringify(migrations, null, 2) +
  ';\n';

writeFileSync(join(root, 'src', 'migrations.generated.ts'), out);
console.log(`Bundled ${migrations.length} migration(s)`);
